pub(super) fn morphed(fraction: f32) -> [Vec2; POINTS] {
    let index = fraction.floor();
    let from = (index as i64).rem_euclid(COUNT as i64) as usize;
    let to = (from + 1) % COUNT;
    let t = (fraction - index).clamp(0.0, 1.0);
    let start = &TABLE[from];
    let end = &TABLE[to];
    std::array::from_fn(|point| Vec2::from(start[point]).lerp(Vec2::from(end[point]), t))
}
